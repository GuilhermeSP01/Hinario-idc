"""Explicit assignment of Silver source entries to stable editorial identities."""
from copy import deepcopy
from uuid import UUID, uuid4
from .editorial import commit_operation, edit_lock, head, ordered
from .layers import load_silver
from .storage import DATA, digest


def exact_keys(value, allowed, required):
    if not isinstance(value, dict) or set(value) - set(allowed) or set(required) - set(value):
        raise ValueError('Invalid reconciliation fields')


def apply_source(parent, operation, data):
    exact_keys(operation, ['type','reason','expectedRevision','datasetId','assignments','remaining'],
               ['type','reason','expectedRevision','datasetId','assignments','remaining'])
    if operation['expectedRevision'] != digest(parent):
        raise ValueError('Editorial precondition changed')
    payload = load_silver(operation['datasetId'], data)
    source = {h['sourceOrdinal']: h for h in payload['hymns']}
    previous = {h['id']: h for h in parent['hymns']}
    assignments, remaining = operation['assignments'], operation['remaining']
    if not isinstance(assignments, list) or not isinstance(remaining, list):
        raise ValueError('Reconciliation requires assignment and remaining lists')
    seen_source, seen_ids, mapping, hymns = set(), set(), {}, []
    for item in assignments:
        exact_keys(item, ['sourceOrdinal','id','use','new','omit'], ['sourceOrdinal'])
        ordinal = item['sourceOrdinal']
        if type(ordinal) is not int or ordinal not in source or ordinal in seen_source:
            raise ValueError('Missing/duplicate/invalid source entry')
        seen_source.add(ordinal)
        if item.get('omit') is True:
            if set(item) != {'sourceOrdinal','omit'}: raise ValueError('Omitted entry has extra fields')
            mapping[str(ordinal)] = None
            continue
        identity = item.get('id')
        if not isinstance(identity, str) or identity in seen_ids:
            raise ValueError('Invalid or duplicate identity mapping')
        seen_ids.add(identity)
        if item.get('new') is True:
            if identity in previous or identity in parent['retiredIds'] or str(UUID(identity, version=4)) != identity:
                raise ValueError('New identity is invalid or already used')
            if item.get('use') != 'source': raise ValueError('New source entry must use source content')
        elif identity not in previous or 'new' in item:
            raise ValueError('Identity must be active or explicitly new')
        if item.get('use') == 'local':
            if identity not in previous: raise ValueError('Local content not found')
            hymn = deepcopy(previous[identity])
        elif item.get('use') == 'source':
            hymn = dict(id=identity, **{k:deepcopy(source[ordinal][k]) for k in ('number','title','sections')})
        else:
            raise ValueError('Choose source or local content explicitly')
        hymns.append(hymn); mapping[str(ordinal)] = identity
    if seen_source != set(source): raise ValueError('Every Silver entry needs an explicit assignment')
    for item in remaining:
        exact_keys(item,['id','action'],['id','action'])
        identity = item['id']
        if identity not in previous or identity in seen_ids: raise ValueError('Invalid remaining identity')
        seen_ids.add(identity)
        if item['action'] == 'keep': hymns.append(deepcopy(previous[identity]))
        elif item['action'] != 'delete': raise ValueError('Choose keep or delete explicitly')
    if set(previous) - seen_ids: raise ValueError('Every current hymn needs an explicit decision')
    result = deepcopy(parent)
    result.update(parent=digest(parent), operation=deepcopy(operation), datasetId=operation['datasetId'],
                  sourceMapping=mapping, hymns=ordered(hymns),
                  retiredIds=sorted(set(parent['retiredIds']) | (set(previous) - {h['id'] for h in hymns})))
    if all(result[k] == parent[k] for k in ('datasetId','sourceMapping','hymns','retiredIds')):
        raise ValueError('No editorial changes')
    return result


def reconcile_source(dataset_id, review, reason, data=DATA):
    exact_keys(review,['expectedRevision','assignments','remaining'],['expectedRevision','assignments','remaining'])
    operation = dict(type='source', reason=reason, datasetId=dataset_id, **deepcopy(review))
    if not isinstance(operation['assignments'],list): raise ValueError('Expected assignment list')
    for item in operation['assignments']:
        if isinstance(item,dict) and item.get('new') is True:
            if 'id' in item: raise ValueError('New IDs are generated by the pipeline')
            item.update(id=str(uuid4()), use='source')
    with edit_lock(data):
        _, parent = head(data)
        rid, result = commit_operation(parent, operation, data)
    return dict(revision=rid, datasetId=dataset_id, hymnCount=len(result['hymns']))


def source_report(dataset_id, data=DATA):
    rid, parent = head(data)
    payload = load_silver(dataset_id,data)
    return dict(expectedRevision=rid, datasetId=dataset_id,
                sourceEntries=payload['hymns'], currentHymns=parent['hymns'],
                assignmentsFormat={'existing':{'sourceOrdinal':1,'id':'001','use':'source'},
                                   'new':{'sourceOrdinal':2,'new':True},
                                   'omit':{'sourceOrdinal':3,'omit':True}},
                remainingFormat={'id':'existing-id','action':'keep'})
